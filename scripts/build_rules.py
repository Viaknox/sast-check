#!/usr/bin/env python3
"""Bundle rules/custom/<area>/<slug>.yaml into dist/rules.yaml (test fixtures excluded).

Needs PyYAML only at build time; dist/rules.yaml is committed so CI/users don't need it.

Contract with the learner agent: rule IDs are permanent. dist/rule-ids.lock lists every ID ever
shipped; the build fails if one disappears. Retire a rule by moving its id to rules/RETIRED.txt.
Every rule must carry metadata.cwe.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--base-lock", help="rule-ids.lock from the base branch; IDs in it can never disappear")
    a = ap.parse_args()
    rules, ids = [], set()
    for f in sorted((ROOT / "rules" / "custom").glob("*/*.yaml")):
        if f.name.endswith(".test.yaml"):
            continue
        for r in yaml.safe_load(f.read_text())["rules"]:
            if r["id"] in ids:
                print(f"duplicate rule id {r['id']} in {f}", file=sys.stderr)
                return 1
            md = r.get("metadata", {})
            if md.get("sast_severity") not in ("critical", "high", "medium", "low"):
                print(f"{r['id']}: metadata.sast_severity missing/invalid", file=sys.stderr)
                return 1
            if not str(md.get("cwe", "")).startswith("CWE-"):
                print(f"{r['id']}: metadata.cwe missing (learner contract)", file=sys.stderr)
                return 1
            ids.add(r["id"])
            rules.append(r)
    lock = ROOT / "dist" / "rule-ids.lock"
    retired_f = ROOT / "rules" / "RETIRED.txt"
    retired = set(retired_f.read_text().split()) if retired_f.exists() else set()
    shipped = set(lock.read_text().split()) if lock.exists() else set()
    # a PR could delete an ID from both the rule and the lock; the base branch's lock catches that
    if a.base_lock and Path(a.base_lock).exists():
        shipped |= set(Path(a.base_lock).read_text().split())
    reused = ids & retired
    if reused:
        print(f"retired rule ids must never be reused: {sorted(reused)}", file=sys.stderr)
        return 1
    gone = shipped - ids - retired
    if gone:
        print(f"rule ids removed or renamed (IDs are permanent): {sorted(gone)}", file=sys.stderr)
        return 1
    out = ROOT / "dist" / "rules.yaml"
    out.parent.mkdir(exist_ok=True)
    header = "# GENERATED by scripts/build_rules.py from rules/custom/ - do not edit. MIT License.\n"
    out.write_text(header + yaml.safe_dump({"rules": rules}, sort_keys=False, width=1000))
    lock.write_text("\n".join(sorted(shipped | ids)) + "\n")
    print(f"wrote {len(rules)} rules to {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
